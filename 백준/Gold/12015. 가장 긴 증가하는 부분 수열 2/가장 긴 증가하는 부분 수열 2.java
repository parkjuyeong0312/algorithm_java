//<풀이>
//입력값을 배열로 받는다.
//그리고, 해당 원소를 차례대로 만들어간다.
//근데 최댓값보다 큰 값이 나오게 되면, 해당 값을 이진탐색을 해서, 대체한다.
//그리고 최종적으로 길이를 출력한다.

class Main {
    public static void main(String[] args) throws IOException {
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        int N = Integer.parseInt(br.readLine());
        int[] arr = new int[N];
        StringTokenizer st = new StringTokenizer(br.readLine());
        
        for(int i=0; i<N; i++){
            arr[i] = Integer.parseInt(st.nextToken());
        }

        // 이진 탐색에 사용할 배열
        int[] permutation = new int[N];
        int index = 0; // 현재까지 만들어진 가장 긴 증가하는 부분 수열의 길이

        for(int i=0; i<N; i++){
            // 첫 원소이거나, 현재 배열의 마지막(가장 큰) 값보다 크면 맨 뒤에 추가
            if(index == 0 || arr[i] > permutation[index - 1]){
                permutation[index++] = arr[i];
            } else { 
                // 작거나 같다면, 이진 탐색으로 들어갈 위치를 찾아 교체 (대치)
                // 배열에 현재 채워진 길이(index)를 같이 넘겨줍니다.
                binarysearch(arr[i], permutation, index);
            }
        }

        // 최종 길이 출력
        System.out.println(index);
    }

    static void binarysearch(int target, int[] permutation, int length){
        int left = 0; 
        int right = length - 1; // 포인트1 수정: 배열 전체가 아니라 현재 채워진 끝까지만 탐색

        while(left < right){ // 포인트2
            int mid = (left + right) / 2;

            if(permutation[mid] < target){
                left = mid + 1;
            } else { // permutation[mid] >= target
                right = mid;
            }            
        }
        // 찾은 위치의 값을 새로운 값으로 교체 (길이는 변하지 않으면서 더 유리한 숫자로 갱신)
        permutation[left] = target;
    }
}































